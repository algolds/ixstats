import type { useThinkpagesPost } from "./useThinkpagesPost";

/** Account/callback props every post view passes down to its actions and replies. */
export interface PostViewContext {
  currentUserAccountId: string;
  accounts?: any[];
  countryId?: string;
  isOwner?: boolean;
  onAccountSelect?: (account: any) => void;
  onAccountSettings?: (account: any) => void;
  onCreateAccount?: () => void;
  onLike?: (postId: string) => void;
  onRepost?: (postId: string) => void;
  onReply?: (postId: string) => void;
  onShare?: (postId: string) => void;
  onReaction?: (postId: string, reactionType: string) => void;
  onAccountClick?: (accountId: string) => void;
}

export type PostState = ReturnType<typeof useThinkpagesPost>;
