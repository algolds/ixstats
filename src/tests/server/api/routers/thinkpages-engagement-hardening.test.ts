describe("thinkpages.pinPost", () => {
  const pin = (db: MockPrismaProxy, clerk: string, level = 100) =>
    createCallerFactory(thinkpagesPostsPostsModifyRouter)(ctxFor(db, clerk, level)).pinPost({
      postId: "p1",
      accountId: "acc_owner",
      pinned: true,
    });

  it("refuses a caller who names the post's account but doesn't own it", async () => {
    const db = createMockPrisma();
    db.thinkpagesPost.findUnique.mockResolvedValue(post());
    await expect(pin(db, ME)).rejects.toMatchObject({ code: "FORBIDDEN" });
    expect(db.thinkpagesPost.update).not.toHaveBeenCalled();
  });

  it("lets the owner and a moderator pin", async () => {
    for (const [clerk, level] of [
      [OWNER, 100],
      [ME, 10],
    ] as const) {
      const db = createMockPrisma();
      db.thinkpagesPost.findUnique.mockResolvedValue(post());
      await pin(db, clerk, level);
      expect(db.thinkpagesPost.update).toHaveBeenCalledWith({
        where: { id: "p1" },
        data: { pinned: true },
      });
    }
  });
});

describe("thinkpages.createPost", () => {
  const me = {
    id: "acc_me",
    clerkUserId: ME,
    isActive: true,
    username: "me",
    displayName: "Me",
    verified: false,
  };
  function setup() {
    const db = createMockPrisma();
    db.thinkpagesAccount.findUnique.mockResolvedValue(me);
    db.thinkpagesPost.create.mockImplementation(async ({ data }: any) => ({
      id: "new",
      ...data,
      account: { ...me },
      parentPost: data.parentPostId ? post({ id: data.parentPostId }) : null,
      repostOf: data.repostOfId ? post({ id: data.repostOfId }) : null,
    }));
    return db;
  }
  const create = (db: MockPrismaProxy, input: Record<string, unknown>) =>
    createCallerFactory(thinkpagesPostsPostsCreateRouter)(ctxFor(db)).createPost({
      accountId: "acc_me",
      postToDiscord: false,
      ...input,
    } as never);

  it.each(["repostOfId", "parentPostId"])(
    "refuses a %s pointing at someone else's private post",
    async (field) => {
      const db = setup();
      db.thinkpagesPost.findUnique.mockResolvedValue(post({ visibility: "private" }));
      await expect(create(db, { content: "x", [field]: "p1" })).rejects.toMatchObject({
        code: "NOT_FOUND",
      });
      expect(db.thinkpagesPost.create).not.toHaveBeenCalled();
    }
  );

  it("reposts a public post and returns it without owner Clerk ids", async () => {
    const db = setup();
    db.thinkpagesPost.findUnique.mockResolvedValue(post());
    const result: any = await create(db, { content: "", repostOfId: "p1" });
    expect(result.repostOf.id).toBe("p1");
    expect(JSON.stringify(result)).not.toContain(OWNER);
    expect(JSON.stringify(result)).not.toContain(ME);
  });

  it("strips a forged Discord marker from the content", async () => {
    const db = setup();
    await create(db, { content: "hi [DiscordMsg:123456] there [discordmsg:9]" });
    expect(db.thinkpagesPost.create.mock.calls[0]![0].data.content).toBe("hi there");
  });

  it("sends nothing to Discord when Share to Discord is off, emotes included", async () => {
    mockMirrorFeed.mockClear();
    mockPostToIxTwitter.mockClear();
    await create(setup(), { content: "hello <:ixwiki:123456789012345678>", postToDiscord: false });
    await new Promise((r) => setTimeout(r, 0));
    expect(mockMirrorFeed).not.toHaveBeenCalled();
    expect(mockPostToIxTwitter).not.toHaveBeenCalled();

    await create(setup(), { content: "hello <:ixwiki:123456789012345678>", postToDiscord: true });
    await new Promise((r) => setTimeout(r, 0));
    expect(mockMirrorFeed).toHaveBeenCalledTimes(1);
    expect(mockPostToIxTwitter).toHaveBeenCalledTimes(1);
  });

  it("looks up only mentions written in the content, at most MENTION_MAX_PER_POST", async () => {
    const db = setup();
    const written = Array.from({ length: MENTION_MAX_PER_POST + 5 }, (_, i) => `user${i}`);
    await create(db, {
      content: written.map((n) => `@${n}`).join(" "),
      mentions: [...written, "notwritten"].map((n) => `@${n}`),
    });
    const names = db.thinkpagesAccount.findMany.mock.calls[0]![0].where.username.in;
    expect(names).toHaveLength(MENTION_MAX_PER_POST);
    expect(names).not.toContain("notwritten");
  });

  it("doesn't notify a parent author who blocked the replier", async () => {
    const db = setup();
    db.thinkpagesPost.findUnique.mockResolvedValue(post());
    blockedBy(db, [OWNER]);
    await create(db, { content: "reply", parentPostId: "p1" });
    expect(db.thinkpagesPost.create).toHaveBeenCalled();
    expect(mockOnThinkPageActivity).not.toHaveBeenCalled();

    const open = setup();
    open.thinkpagesPost.findUnique.mockResolvedValue(post());
    await create(open, { content: "reply", parentPostId: "p1" });
    expect(mockOnThinkPageActivity).toHaveBeenCalledTimes(1);
  });

  it("doesn't notify an original author who blocked the reposter", async () => {
    const db = setup();
    db.thinkpagesPost.findUnique.mockResolvedValue(post());
    blockedBy(db, [OWNER]);
    await create(db, { content: "", repostOfId: "p1" });
    expect(mockOnSocialActivity).not.toHaveBeenCalled();
  });
});

describe("thinkpages.updatePost and the Discord marker", () => {
  it("keeps the post's own marker and drops one typed by the user", async () => {
    const db = createMockPrisma();
    db.thinkpagesPost.findUnique.mockResolvedValue(
      post({ content: "old\n\n[DiscordMsg:111]", account: { clerkUserId: OWNER } })
    );
    db.thinkpagesPost.update.mockImplementation(async ({ data }: any) => ({
      ...post(),
      ...data,
      mediaAttachments: [],
    }));
    const result: any = await createCallerFactory(thinkpagesPostsPostsModifyRouter)(
      ctxFor(db, OWNER)
    ).updatePost({ postId: "p1", content: "new [DiscordMsg:999]" });
    expect(db.thinkpagesPost.update.mock.calls[0]![0].data.content).toBe("new\n\n[DiscordMsg:111]");
    expect(result.account.clerkUserId).toBeUndefined();
  });

  it("stripDiscordMarker leaves other brackets alone", () => {
    expect(stripDiscordMarker("[b]bold[/b] [DiscordMsg:]")).toBe("[b]bold[/b]");
  });
});

