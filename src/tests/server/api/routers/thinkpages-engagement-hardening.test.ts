/**
 * ThinkPages engagement hardening:
 * - pinPost is the post owner's (or a moderator's), not anyone naming the post's account id;
 * - a reply or repost needs a post the caller can read, and embedded private parents/originals are
 *   dropped from the feed and saved posts;
 * - mentions count only when written in the content, at most MENTION_MAX_PER_POST;
 * - a `[DiscordMsg:<id>]` marker in user content is stripped (only the IxTwitter sync sets one);
 * - replies, likes, reposts and follows notify nobody who blocked the actor, a blocked user can't
 *   follow, and a follow/unfollow loop notifies once;
 * - the public reactions list is bounded and its Discord part cached;
 * - public persona, post, member and blurb responses carry no Clerk ids.
 *
 * `jest` is the ambient global because the hoisted jest.mock() factories call jest.fn() inline.
 */
