describe("blocks on likes and follows", () => {
  it("a like doesn't notify an author who blocked the liker", async () => {
    const db = createMockPrisma();
    db.thinkpagesAccount.findUnique.mockResolvedValue({ id: "acc_me", clerkUserId: ME });
    db.thinkpagesPost.findUnique.mockResolvedValue(post());
    db.postReaction.findUnique.mockResolvedValue(null);
    blockedBy(db, [OWNER]);
    await createCallerFactory(thinkpagesPostsReactionsMutationsRouter)(ctxFor(db)).addReaction({
      postId: "p1",
      accountId: "acc_me",
      reactionType: "like",
    });
    expect(db.postReaction.create).toHaveBeenCalled();
    expect(mockOnThinkPageActivity).not.toHaveBeenCalled();
  });

  it("refuses a reaction to a post the reactor can't read", async () => {
    const db = createMockPrisma();
    db.thinkpagesAccount.findUnique.mockResolvedValue({ id: "acc_me", clerkUserId: ME });
    db.thinkpagesPost.findUnique.mockResolvedValue(post({ visibility: "private" }));
    await expect(
      createCallerFactory(thinkpagesPostsReactionsMutationsRouter)(ctxFor(db)).addReaction({
        postId: "p1",
        accountId: "acc_me",
        reactionType: "like",
      })
    ).rejects.toMatchObject({ code: "NOT_FOUND" });
    expect(db.postReaction.create).not.toHaveBeenCalled();
  });

  const target = { id: "acc_owner", clerkUserId: OWNER, username: "owner", isActive: true };
  const mine = { id: "acc_me", clerkUserId: ME, username: "me", displayName: "Me", isActive: true };
  function followDb() {
    const db = createMockPrisma();
    db.thinkpagesAccount.findUnique.mockImplementation(async ({ where }: any) =>
      where.id === "acc_owner" ? target : mine
    );
    return db;
  }
  const follow = (db: MockPrismaProxy) =>
    createCallerFactory(activitiesFollowsRouter)(ctxFor(db)).followPersona({
      accountId: "acc_owner",
      followerAccountId: "acc_me",
    });

  it("refuses to follow someone who blocked you", async () => {
    const db = followDb();
    blockedBy(db, [OWNER]);
    await expect(follow(db)).rejects.toMatchObject({ code: "FORBIDDEN" });
    expect(db.thinkpagesFollow.create).not.toHaveBeenCalled();
  });

  it("notifies a new follower once, not again after an unfollow/follow loop", async () => {
    const db = followDb();
    await follow(db);
    expect(mockNotificationCreate).toHaveBeenCalledTimes(1);
    const { metadata } = mockNotificationCreate.mock.calls[0]![0] as any;
    expect(metadata.followKey).toBe("acc_me:acc_owner");

    db.notification.findFirst.mockResolvedValue({ id: "n1" });
    await follow(db);
    expect(mockNotificationCreate).toHaveBeenCalledTimes(1);
    expect(db.notification.findFirst.mock.calls[1]![0].where).toMatchObject({
      userId: OWNER,
      metadata: { contains: '"followKey":"acc_me:acc_owner"' },
    });
  });
});

describe("thinkpages.getPostReactions", () => {
  const read = (db: MockPrismaProxy, clerk: string | null = null) =>
    createCallerFactory(thinkpagesPostsReactionsQueriesRouter)(ctxFor(db, clerk)).getPostReactions({
      postId: "p1",
    });

  it("bounds the local list and lists nothing for a post the viewer can't read", async () => {
    const db = createMockPrisma();
    db.thinkpagesPost.findUnique.mockResolvedValue(post());
    await read(db);
    expect(db.postReaction.findMany.mock.calls[0]![0].take).toBe(200);

    const hidden = createMockPrisma();
    hidden.thinkpagesPost.findUnique.mockResolvedValue(post({ visibility: "private" }));
    expect(await read(hidden)).toEqual([]);
    expect(hidden.postReaction.findMany).not.toHaveBeenCalled();
  });

  it("serves a synced post's Discord reactors from the cache without calling Discord", async () => {
    const fetchSpy = jest.spyOn(global, "fetch");
    process.env.DISCORD_BOT_TOKEN = "token";
    try {
      const db = createMockPrisma();
      db.thinkpagesPost.findUnique.mockResolvedValue(
        post({ content: "hi\n\n[DiscordMsg:42]", reactionCounts: JSON.stringify({ like: 3 }) })
      );
      mockCacheGet.mockResolvedValue([{ id: "discord_react_1_like" }]);
      const result = await read(db);
      expect(result).toEqual([{ id: "discord_react_1_like" }]);
      expect(mockCacheGet).toHaveBeenCalledWith("thinkpages_discord_reactions:42:all");
      expect(fetchSpy).not.toHaveBeenCalled();
    } finally {
      delete process.env.DISCORD_BOT_TOKEN;
      fetchSpy.mockRestore();
    }
  });

  it("caps the Discord reactors it resolves and caches the list", async () => {
    process.env.DISCORD_BOT_TOKEN = "token";
    const reactors = Array.from({ length: 80 }, (_, i) => ({ id: `${i}`, username: `u${i}` }));
    const fetchSpy = jest
      .spyOn(global, "fetch")
      .mockResolvedValue(new Response(JSON.stringify(reactors), { status: 200 }));
    try {
      const db = createMockPrisma();
      db.thinkpagesPost.findUnique.mockResolvedValue(
        post({ content: "hi\n\n[DiscordMsg:42]", reactionCounts: JSON.stringify({ like: 80 }) })
      );
      const result = await read(db);
      expect(result).toHaveLength(50);
      expect(String(fetchSpy.mock.calls[0]![0])).toContain("limit=50");
      expect(mockCacheSet).toHaveBeenCalledWith(
        "thinkpages_discord_reactions:42:all",
        expect.any(Array),
        { ttl: 120 }
      );
    } finally {
      delete process.env.DISCORD_BOT_TOKEN;
      fetchSpy.mockRestore();
    }
  });
  it("does not cache a read where Discord refused an emoji (429)", async () => {
    process.env.DISCORD_BOT_TOKEN = "token";
    const fetchSpy = jest
      .spyOn(global, "fetch")
      .mockResolvedValue(new Response("rate limited", { status: 429 }));
    try {
      const db = createMockPrisma();
      db.thinkpagesPost.findUnique.mockResolvedValue(
        post({ content: "hi\n\n[DiscordMsg:42]", reactionCounts: JSON.stringify({ like: 3 }) })
      );
      await read(db);
      expect(mockCacheSet).not.toHaveBeenCalledWith(
        "thinkpages_discord_reactions:42:all",
        expect.anything(),
        expect.anything()
      );
    } finally {
      delete process.env.DISCORD_BOT_TOKEN;
      fetchSpy.mockRestore();
    }
  });
});

describe("public responses carry no Clerk ids", () => {
  it("getAccountsByCountry says which personas are the viewer's instead", async () => {
    const db = createMockPrisma();
    db.thinkpagesAccount.findMany.mockResolvedValue([
      { id: "a1", clerkUserId: OWNER, username: "owner" },
      { id: "a2", clerkUserId: ME, username: "me" },
    ]);
    const accounts = await createCallerFactory(thinkpagesAccountsRouter)(
      ctxFor(db)
    ).getAccountsByCountry({ countryId: "c1" });
    expect(accounts).toEqual([
      { id: "a1", username: "owner", isMine: false },
      { id: "a2", username: "me", isMine: true },
    ]);
  });

  it("the global activity feed selects no persona Clerk id and drops embedded private posts", async () => {
    const db = createMockPrisma();
    db.postReaction.groupBy.mockResolvedValue([]);
    const feedPost = (over: Record<string, unknown>) => ({
      ...post(over),
      account: { id: "acc_owner", username: "owner", country: null },
      mediaAttachments: [],
      poll: null,
    });
    db.thinkpagesPost.findMany.mockResolvedValue([
      feedPost({
        id: "r1",
        repostOf: { ...post({ id: "secret", visibility: "private", content: "s3cret" }) },
      }),
    ]);
    const { activities } = await createCallerFactory(activitiesFeedGlobalRouter)(
      ctxFor(db, null)
    ).getGlobalFeed({ filter: "social", limit: 10 } as never);
    const include = db.thinkpagesPost.findMany.mock.calls[0]![0].include;
    expect(JSON.stringify(include)).not.toContain("clerkUserId");
    const item = activities.find((a: any) => a.source === "thinkpages") as any;
    expect(item.rawPost.repostOf).toBeNull();
    expect(JSON.stringify(activities)).not.toContain("s3cret");
  });

  it("users.getActiveUsers names members by nation, with no last-active time", async () => {
    const db = createMockPrisma();
    db.user.findMany.mockResolvedValue([
      {
        clerkUserId: OWNER,
        countryId: "c1",
        country: { name: "Alpha" },
        updatedAt: new Date(),
        createdAt: new Date(),
      },
    ]);
    const users = await createCallerFactory(usersAdminRouter)(ctxFor(db)).getActiveUsers({
      limit: 5,
      excludeUserId: "someone",
    });
    expect(users[0]).toMatchObject({ id: "c1", countryName: "Alpha" });
    expect(users[0]).not.toHaveProperty("lastActive");
    expect(JSON.stringify(users)).not.toContain(OWNER);
    expect(db.user.findMany.mock.calls[0]![0].where.clerkUserId).toEqual({ not: ME });
  });

  it("users.getUserWithRole reads a persona's owner level without the client knowing their id", async () => {
    const db = createMockPrisma();
    db.thinkpagesAccount.findUnique.mockResolvedValue({ clerkUserId: OWNER });
    db.user.findUnique.mockResolvedValue({ role: { level: 20 } });
    const result = await createCallerFactory(usersProfileRouter)(ctxFor(db)).getUserWithRole({
      thinkpagesAccountId: "acc_owner",
    });
    expect(result).toEqual({ roleLevel: 20 });
    expect(db.user.findUnique.mock.calls[0]![0].where).toEqual({ clerkUserId: OWNER });
  });
});
