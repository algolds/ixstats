const ME = "clerk_me";
const OWNER = "clerk_owner";

function ctxFor(db: MockPrismaProxy, clerk: string | null = ME, level = 100) {
  return createMockRouterContext({
    db,
    auth: clerk ? { userId: clerk } : null,
    user: clerk ? { id: `db_${clerk}`, clerkUserId: clerk, role: { name: "user", level } } : null,
  }) as never;
}

/** A db where `blockers` have blocked the caller. */
function blockedBy(db: MockPrismaProxy, blockers: string[]) {
  db.userConnection.findMany.mockImplementation(async (args: any) =>
    args?.where?.connectionType === "blocked"
      ? blockers.filter((b) => args.where.userId?.in?.includes(b)).map((userId) => ({ userId }))
      : []
  );
}

