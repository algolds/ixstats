/**
 * Distinctive typographical currency symbols for currencies without a single-character glyph
 * in ccy-icons (e.g. Canadian Dollar CA$, Australian Dollar A$, Swiss Franc Fr, Chinese Yuan 元).
 * Eliminates duplicate icons without using country flags.
 */
const DISTINCT_SYMBOLS: Record<string, string> = {
  CAD: "CA$",
  AUD: "A$",
  CHF: "Fr",
  CNY: "元",
  NZD: "NZ$",
  SGD: "S$",
  HKD: "HK$",
  MXN: "Mex$",
  BRL: "R$",
  SEK: "kr",
  NOK: "kr",
  ZAR: "R",
};

/**
 * CurrencyIcon renders an authentic currency symbol for fiat, crypto, and sovereign presets,
 * combining DominicTobias/ccy-icons vector glyphs with distinctive typographical symbols.
 * Zero country flags — exclusively pure currency symbols.
 */
export const CurrencyIcon = React.memo(function CurrencyIcon({
  code,
  symbol,
  className,
  fallbackToSymbol = true,
  ...props
}: CurrencyIconProps) {
  const cleanCode = code ? code.trim().toUpperCase() : "";
  const cleanSymbol = symbol ? symbol.trim() : "";

  // 1. Authentic CCY vector library (USD, EUR, GBP, JPY, INR, RUB, TRY, DKK, IDR, SAR, KRW, BTC, ETH, USDT, USDC, BNB, XRP, ADA, DOGE, LTC, DAI, XMR, and sovereign lore)
  const vector = cleanCode && cleanCode in CCY_VECTORS ? CCY_VECTORS[cleanCode] : undefined;
  if (vector) {
    return (
      <span
        className={cn(
          "inline-flex items-center justify-center shrink-0 leading-none overflow-hidden",
          className
        )}
        {...props}
      >
        <svg
          viewBox={vector.viewBox}
          fill="currentColor"
          xmlns="http://www.w3.org/2000/svg"
          className="h-full w-full max-h-full max-w-full object-contain"
          aria-hidden="true"
        >
          <path d={vector.path} fillRule={vector.fillRule} />
        </svg>
      </span>
    );
  }

  // 2. Distinctive currency symbols for non-duplicate fiat currencies (CAD -> CA$, AUD -> A$, CHF -> Fr, CNY -> 元, etc.)
  const symbolText =
    (cleanCode && cleanCode in DISTINCT_SYMBOLS ? DISTINCT_SYMBOLS[cleanCode] : undefined) ||
    (fallbackToSymbol && cleanSymbol ? cleanSymbol : undefined);

  if (symbolText) {
    const fontSizeClass =
      symbolText.length >= 4
        ? "text-[8.5px]"
        : symbolText.length === 3
        ? "text-[9.5px]"
        : "text-[11px]";

    return (
      <span
        className={cn(
          "inline-flex items-center justify-center shrink-0 font-mono font-bold leading-none select-none tracking-tight",
          fontSizeClass,
          className
        )}
        {...props}
      >
        {symbolText}
      </span>
    );
  }

  // 3. Fallback: generic Coins icon
  return (
    <span
      className={cn(
        "inline-flex items-center justify-center shrink-0 leading-none",
        className
      )}
      {...props}
    >
      <Coins className="h-full w-full opacity-70" aria-hidden="true" />
    </span>
  );
});
