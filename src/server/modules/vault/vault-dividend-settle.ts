import type { PrismaClient } from "@prisma/client";
import { scoredEditsAccount } from "~/lib/lorewards/resolve-user";
import { scoreDailyWikiOS } from "~/lib/lorewards/scoring";
import { EXCLUDE_TROPHY_CARDS } from "~/lib/lorewards/trophy-cards";
import {
  DIVIDEND,
  computeDividend,
  dividendKey,
  shiftDay,
  utcDay,
  type DividendInputs,
} from "~/lib/vault/vault-dividend";
import { getYieldBoostMultiplier } from "~/lib/vault/vault-perks";
import { earnCreditsOnce } from "~/lib/vault/vault-service";
import { readConfigKeys, writeConfigKeys } from "~/server/shared/config-kv";

/** Per-user figures keyed by `User.id`. */
type Counts = Map<string, number>;
type DayRange = { gte: Date; lt: Date };

const CARD_SALE_SOURCES = ["card_sale_auction", "card_sale_buyout"];
const DIVIDEND_SOURCE = "VAULT_DIVIDEND";
/** SystemConfig key holding the first day the dividend settled (`yyyy-mm-dd`); no earlier day is ever settled. */
const DIVIDEND_START_KEY = "vault_dividend_started_on";

function dayRange(day: string): DayRange {
  const gte = new Date(`${day}T00:00:00.000Z`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(day) || utcDay(gte) !== day)
    throw new Error(`Dividend day must be yyyy-mm-dd, got "${day}"`);
  return { gte, lt: new Date(`${shiftDay(day, 1)}T00:00:00.000Z`) };
}

const add = (counts: Counts, userId: string, n: number) =>
  counts.set(userId, (counts.get(userId) ?? 0) + n);

/**
 * Sum of each editor's Lorewards candidate scores for the day, by account. A candidate (one name's edits to one page
 * that day) is credited from its scored revisions themselves (`scoredEditsAccount`): the one WikiOS account on all
 * of them, else, when all came from MediaWiki, the name's exact verified-link holder. Mixed revisions, or MediaWiki
 * edits with no link, earn no wiki part.
 */
async function loadWikiScores(db: PrismaClient, day: string): Promise<Counts> {
  const { candidates } = await scoreDailyWikiOS(day, undefined, { enrichAll: true });
  const scores: Counts = new Map();
  for (const c of candidates) {
    const userId = await scoredEditsAccount(db, c.user, c.authorIds);
    if (userId) add(scores, userId, c.finalScore);
  }
  return scores;
}

/** Human ThinkPages posts (by Clerk id, mapped to `User.id`) plus visible forum posts and replies. */
async function loadPostCounts(db: PrismaClient, range: DayRange): Promise<Counts> {
  const counts: Counts = new Map();
  const forum = await db.forumPost.groupBy({
    by: ["authorUserId"],
    where: { authorUserId: { not: null }, hidden: false, createdAt: range },
    _count: { _all: true },
  });
  for (const row of forum) if (row.authorUserId) add(counts, row.authorUserId, row._count._all);

  const posts = await db.thinkpagesPost.groupBy({
    by: ["accountId"],
    where: { isAutoGenerated: false, postType: { not: "repost" }, createdAt: range },
    _count: { _all: true },
  });
  if (posts.length === 0) return counts;
  const accounts = await db.thinkpagesAccount.findMany({
    where: { id: { in: posts.map((p) => p.accountId) } },
    select: { id: true, clerkUserId: true },
  });
  const users = await db.user.findMany({
    where: { clerkUserId: { in: accounts.map((a) => a.clerkUserId) } },
    select: { id: true, clerkUserId: true },
  });
  const userByClerk = new Map(users.map((u) => [u.clerkUserId, u.id]));
  const clerkByAccount = new Map(accounts.map((a) => [a.id, a.clerkUserId]));
  for (const row of posts) {
    const userId = userByClerk.get(clerkByAccount.get(row.accountId) ?? "");
    if (userId) add(counts, userId, row._count._all);
  }
  return counts;
}

async function loadPacksOpened(db: PrismaClient, range: DayRange): Promise<Counts> {
  const rows = await db.userPack.groupBy({
    by: ["userId"],
    where: { isOpened: true, openedAt: range },
    _count: { _all: true },
  });
  return new Map(rows.map((r) => [r.userId, r._count._all]));
}

/** An accepted trade counts for both sides. */
async function loadTradesCompleted(db: PrismaClient, range: DayRange): Promise<Counts> {
  const counts: Counts = new Map();
  const where = { status: "ACCEPTED", respondedAt: range };
  const asInitiator = await db.tradeOffer.groupBy({
    by: ["initiatorId"],
    where,
    _count: { _all: true },
  });
  const asRecipient = await db.tradeOffer.groupBy({
    by: ["recipientId"],
    where,
    _count: { _all: true },
  });
  for (const r of asInitiator) add(counts, r.initiatorId, r._count._all);
  for (const r of asRecipient) add(counts, r.recipientId, r._count._all);
  return counts;
}

/** Listings sold, read from the seller's card-sale ledger rows. */
async function loadListingsSold(db: PrismaClient, range: DayRange): Promise<Counts> {
  const sales = await db.vaultTransaction.findMany({
    where: { type: "EARN_CARDS", source: { in: CARD_SALE_SOURCES }, createdAt: range },
    select: { vault: { select: { userId: true } } },
  });
  const counts: Counts = new Map();
  for (const sale of sales) add(counts, sale.vault.userId, 1);
  return counts;
}

/** Each owner's card deck value now (market value x quantity; retired and Loreward trophy cards excluded). */
async function loadDeckValues(db: PrismaClient): Promise<Counts> {
  const owned = await db.cardOwnership.findMany({
    where: { cards: { isRetired: false, ...EXCLUDE_TROPHY_CARDS } },
    select: { ownerId: true, quantity: true, cards: { select: { marketValue: true } } },
  });
  const values: Counts = new Map();
  for (const o of owned) add(values, o.ownerId, o.cards.marketValue * o.quantity);
  return values;
}

/** The streak still in force on `day`: a login the day before or later keeps it, otherwise it has lapsed. */
function effectiveStreak(
  vault: { loginStreak: number; lastLoginDate: Date | null },
  day: string
): number {
  if (!vault.lastLoginDate) return 0;
  return utcDay(vault.lastLoginDate) >= shiftDay(day, -1) ? vault.loginStreak : 0;
}

/** Pays one user's dividend: `paid` when a new row was written, `skipped` when it already existed or failed. */
async function payDividend(
  db: PrismaClient,
  userId: string,
  day: string,
  inputs: DividendInputs
): Promise<"paid" | "skipped"> {
  const { total, lines } = computeDividend(inputs);
  const result = await earnCreditsOnce(db, {
    userId,
    amount: total,
    type: "EARN_PASSIVE",
    source: DIVIDEND_SOURCE,
    metadata: { day, lines, inputs },
    idempotencyKey: dividendKey(userId, day),
  });
  if (result.success) return result.alreadyApplied ? "skipped" : "paid";
  console.error(`[VaultDividend] ${userId} ${day}: ${result.message ?? "payout failed"}`);
  return "skipped";
}

/**
 * Settle one UTC day (`yyyy-mm-dd`): every vault with something to pay gets one itemised, idempotent payout.
 * `skipped` counts payouts already applied and payouts that failed (logged; a day that wrote no row is retried
 * by `settleMissedDividends`). Deck value and the streak are read at settle time, a known ceiling for missed days.
 */
export async function settleDividendDay(
  db: PrismaClient,
  day: string
): Promise<{ paid: number; skipped: number }> {
  const range = dayRange(day);
  const [wiki, posts, packs, trades, sold, deck, vaults] = await Promise.all([
    loadWikiScores(db, day),
    loadPostCounts(db, range),
    loadPacksOpened(db, range),
    loadTradesCompleted(db, range),
    loadListingsSold(db, range),
    loadDeckValues(db),
    db.myVault.findMany({ select: { userId: true, loginStreak: true, lastLoginDate: true } }),
  ]);

  let paid = 0;
  let skipped = 0;
  for (const vault of vaults) {
    const id = vault.userId;
    const figures = {
      deckValue: deck.get(id) ?? 0,
      wikiScore: wiki.get(id) ?? 0,
      posts: posts.get(id) ?? 0,
      packsOpened: packs.get(id) ?? 0,
      tradesCompleted: trades.get(id) ?? 0,
      listingsSold: sold.get(id) ?? 0,
    };
    if (Object.values(figures).every((n) => n <= 0)) continue;
    try {
      const inputs: DividendInputs = {
        ...figures,
        streakDays: effectiveStreak(vault, day),
        yieldBoost: await getYieldBoostMultiplier(id, db),
      };
      if (computeDividend(inputs).total <= 0) continue;
      if ((await payDividend(db, id, day, inputs)) === "paid") paid++;
      else skipped++;
    } catch (error) {
      console.error(`[VaultDividend] ${id} ${day}:`, error);
      skipped++;
    }
  }
  return { paid, skipped };
}

/** A day is settled once any dividend row for it exists. */
async function isDaySettled(db: PrismaClient, day: string): Promise<boolean> {
  const row = await db.vaultTransaction.findFirst({
    where: {
      type: "EARN_PASSIVE",
      source: DIVIDEND_SOURCE,
      createdAt: { gte: dayRange(shiftDay(day, 1)).gte },
      idempotencyKey: { endsWith: `:${day}` },
    },
    select: { id: true },
  });
  return row !== null;
}

async function readDividendStart(db: PrismaClient): Promise<string | null> {
  return (await readConfigKeys(db, [DIVIDEND_START_KEY]))[DIVIDEND_START_KEY] ?? null;
}

/**
 * Record `day` as the dividend's start on the first run and return the stored start. An existing start is never
 * moved, so deploy night does not back-pay days the old nation job already paid.
 */
export async function recordDividendStart(db: PrismaClient, day: string): Promise<string> {
  const stored = await readDividendStart(db);
  if (stored) return stored;
  await writeConfigKeys(
    db,
    [{ key: DIVIDEND_START_KEY, value: day }],
    () => "First day the Vault dividend settled; earlier days are never back-paid"
  );
  return day;
}

/**
 * The nightly job settles yesterday; this settles the unsettled days among the 7 before it, oldest first, each
 * from that day's own activity, and never a day earlier than the recorded start. Returns the days it settled.
 */
export async function settleMissedDividends(
  db: PrismaClient,
  now: Date
): Promise<{ days: string[] }> {
  const start = await readDividendStart(db);
  const days: string[] = [];
  if (!start) return { days };
  const yesterday = shiftDay(utcDay(now), -1);
  for (let back = DIVIDEND.MISSED_DAYS; back >= 1; back--) {
    const day = shiftDay(yesterday, -back);
    if (day < start || (await isDaySettled(db, day))) continue;
    await settleDividendDay(db, day);
    days.push(day);
  }
  return { days };
}
