#!/usr/bin/env node
import { execSync } from "child_process";
import { writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

function getGitShort() {
  try {
    const out = execSync("git rev-parse --short=5 HEAD", { encoding: "utf8" });
    return out.trim();
  } catch (e) {
    return null;
  }
}

const v = getGitShort() || "local";
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const dest = path.join(__dirname, "..", "src", "lib", "buildVersion.generated.ts");
const content = `// Auto-generated by scripts/write-build-version.js
export const BUILD_VERSION = "${v}";
`;
writeFileSync(dest, content, "utf8");
console.log("Wrote build version:", v);
